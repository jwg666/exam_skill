{
  const dims = Object.keys(mbtiItems);
  const n = Math.max(...dims.map((d) => mbtiItems[d].length));
  for (let r = 0; r < n; r++) {
    for (const dim of dims) {
      const item = mbtiItems[dim][r];
      if (item) MBTI.push({ q: item[0], opts: [item[1], item[2]], meta: { dim, poles: poles[dim] } });
    }
  }
}

